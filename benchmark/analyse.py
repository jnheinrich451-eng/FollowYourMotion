#!/usr/bin/env python
"""Turn collect.py's per-cell scores into the chapter's tables.

Emits markdown, so the output pastes straight into the thesis and every number
is regenerable from the CSV. Re-run after the masked pass and the tables update
themselves rather than being retyped.

    python benchmark/analyse.py --scores benchmark/scores_davis.csv \
        --out benchmark/tables_davis.md

Four outputs, matching docs/benchmark-results-v1.md section 4:

  Gate      C1 (frozen video) against the best method, per metric. Any metric
            C1 is not clearly beaten on leaves the main table.
  Table 1   Descriptive: configs x metrics, mean + bootstrap CI. No bolding --
            see the ranking section for why a "best" is not identified.
  Table 2   Paired contrasts against a reference config. This is where claims
            live: pairing removes between-clip variance, the dominant term.
  Ranking   Bootstrap over clips: how often each config ranks first. If no
            config wins reliably, an ordering claim is not supported at this N.

Statistical treatment, per docs/fix_on_pipeline.md 2(b): the unit is the clip, not
the run; comparisons are paired on clip; uncertainty is a percentile bootstrap
over clips; a difference counts only when the interval excludes zero.
"""

import argparse
import csv
import random
import statistics as st
import sys
from collections import defaultdict

# Metrics in claim-priority order. Only those present in the CSV are reported,
# so the same script serves the whole-frame pass and the masked one.
METRICS = ["mf", "mf_masked", "dir_cos", "dir_cos_masked", "iq", "temp_cons",
           "subject_consistency", "clip_i_subject", "lpips_bg"]

# Lower is better for these, so the C1 gate compares in the other direction.
LOWER_BETTER = {"lpips_bg"}

CONTROL = "C1"


def boot_ci(vals, stat=st.mean, n=10000, seed=1, alpha=0.05):
    """Percentile bootstrap interval. Resamples clips, which is the unit."""
    rng = random.Random(seed)
    draws = sorted(stat([rng.choice(vals) for _ in vals]) for _ in range(n))
    return draws[int(alpha / 2 * n)], draws[int((1 - alpha / 2) * n)]


def load(path):
    rows = list(csv.DictReader(open(path, newline="", encoding="utf-8")))
    if not rows:
        sys.exit(f"{path} has no rows")
    present = [m for m in METRICS if m in rows[0]]
    for r in rows:
        for m in present:
            v = (r.get(m) or "").strip()
            r[m] = float(v) if v and v.lower() != "nan" else None
    return rows, present


def by_config(rows):
    d = defaultdict(list)
    for r in rows:
        d[r["config"]].append(r)
    return d


def balanced_clips(rows, cfgs):
    """Clips where every config completed.

    Rank comparisons need this: a config missing on a hard clip would otherwise
    look better than one that attempted it and scored badly.
    """
    per = {c: {r["clip_id"] for r in rows if r["config"] == c} for c in cfgs}
    return sorted(set.intersection(*per.values())) if per else []


def fmt(v, nd=3):
    return "--" if v is None else f"{v:.{nd}f}"


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--scores", required=True, help="collect.py output CSV")
    ap.add_argument("--out", help="markdown file (default: stdout)")
    ap.add_argument("--reference", default="backbone",
                    help="config the paired contrasts are measured against")
    ap.add_argument("--primary", default="mf",
                    help="metric used for the bootstrap ranking")
    ap.add_argument("--boot", type=int, default=10000)
    ap.add_argument("--split", help="restrict to one split")
    args = ap.parse_args()

    rows, metrics = load(args.scores)
    if args.split:
        rows = [r for r in rows if r["split"] == args.split]
    out = []
    w = out.append

    groups = by_config(rows)
    methods = [c for c in groups if c != CONTROL]
    w(f"<!-- generated by benchmark/analyse.py from {args.scores} -->\n")
    w(f"{len(rows)} cells | {len(methods)} configs | "
      f"{len({r['clip_id'] for r in rows})} clips | metrics: {', '.join(metrics)}\n")

    # ---------------------------------------------------------------- gate ---
    if CONTROL in groups:
        w(f"\n## Gate: {CONTROL} (degenerate control) vs the best method\n")
        w("| metric | C1 | best method | gap | method cells C1 beats | verdict |")
        w("|---|---|---|---|---|---|")
        for m in metrics:
            c1 = [r[m] for r in groups[CONTROL] if r[m] is not None]
            if not c1:
                continue
            lower = m in LOWER_BETTER
            means = {c: st.mean([r[m] for r in groups[c] if r[m] is not None])
                     for c in methods
                     if any(r[m] is not None for r in groups[c])}
            if not means:
                continue
            best_c = (min if lower else max)(means, key=means.get)
            c1m, bm = st.mean(c1), means[best_c]
            gap = (c1m - bm) if lower else (bm - c1m)
            cells = [r[m] for r in rows if r["config"] != CONTROL and r[m] is not None]
            med = st.median(c1)
            beaten = sum(1 for v in cells if (v >= med if lower else v <= med))
            pct = 100 * beaten / len(cells)
            verdict = "**DROP**" if gap <= 0 else ("suspect" if pct > 25 else "keep")
            w(f"| `{m}` | {fmt(c1m)} | {best_c} {fmt(bm)} | {gap:+.3f} | "
              f"{beaten}/{len(cells)} ({pct:.0f}%) | {verdict} |")
        w("\nA metric the control is not clearly beaten on measures something "
          "other than the task. It leaves the main table.\n")

    # ------------------------------------------------------------- table 1 ---
    w("\n## Table 1 — descriptive (mean over clips, 95% bootstrap CI)\n")
    w("| config | n | " + " | ".join(f"`{m}`" for m in metrics) + " |")
    w("|---" * (len(metrics) + 2) + "|")
    order = [c for c in ["ditflow_z", "ditflow_rho", "smm", "moft", "injection",
                         "backbone"] if c in groups]
    order += [c for c in groups if c not in order and c != CONTROL]
    if CONTROL in groups:
        order.append(CONTROL)
    for c in order:
        cells = []
        for m in metrics:
            v = [r[m] for r in groups[c] if r[m] is not None]
            if not v:
                cells.append("--")
                continue
            lo, hi = boot_ci(v, n=args.boot)
            cells.append(f"{st.mean(v):.3f} [{lo:.3f}, {hi:.3f}]")
        w(f"| {c} | {len(groups[c])} | " + " | ".join(cells) + " |")
    w("\nNo values are bolded: see the ranking section — the top rank is not "
      "identified at this sample size, so marking one would assert more than "
      "the data supports.\n")

    # ------------------------------------------------------------- table 2 ---
    ref = args.reference
    if ref in groups:
        idx = {(r["config"], r["clip_id"]): r for r in rows}
        clips = balanced_clips(rows, methods)
        w(f"\n## Table 2 — paired contrasts vs `{ref}` "
          f"({len(clips)} clips where every config completed)\n")
        w("| contrast | metric | median Δ | mean Δ | 95% CI | excludes 0 |")
        w("|---|---|---|---|---|---|")
        for c in order:
            if c in (ref, CONTROL):
                continue
            for m in metrics:
                d = [idx[(c, cl)][m] - idx[(ref, cl)][m] for cl in clips
                     if (c, cl) in idx and (ref, cl) in idx
                     and idx[(c, cl)][m] is not None and idx[(ref, cl)][m] is not None]
                if len(d) < 3:
                    continue
                lo, hi = boot_ci(d, n=args.boot)
                sig = "**yes**" if (lo > 0 or hi < 0) else "no"
                w(f"| {c} - {ref} | `{m}` | {st.median(d):+.3f} | {st.mean(d):+.3f} | "
                  f"[{lo:+.3f}, {hi:+.3f}] | {sig} |")
        w("\nPairing removes between-clip variance, which dominates. Report the "
          "median alongside the mean: where they diverge the effect is "
          "concentrated in a few clips rather than spread across them.\n")

    # ------------------------------------------------------------- ranking ---
    m = args.primary
    clips = balanced_clips(rows, methods)
    if clips and m in metrics:
        idx = {(r["config"], r["clip_id"]): r for r in rows}
        usable = [c for c in methods
                  if all((c, cl) in idx and idx[(c, cl)][m] is not None for cl in clips)]
        rng = random.Random(0)
        wins = defaultdict(int)
        for _ in range(args.boot):
            samp = [rng.choice(clips) for _ in clips]
            means = {c: st.mean([idx[(c, cl)][m] for cl in samp]) for c in usable}
            wins[max(means, key=means.get)] += 1
        w(f"\n## Ranking — bootstrap over clips, P(ranked first on `{m}`)\n")
        w("| config | P(first) |")
        w("|---|---|")
        for c, n in sorted(wins.items(), key=lambda t: -t[1]):
            w(f"| {c} | {100 * n / args.boot:.1f}% |")
        top = max(wins.values()) / args.boot
        w("")
        if top < 0.9:
            w(f"No config wins reliably (best is {100*top:.0f}%). The between-method "
              f"differences on `{m}` are smaller than the between-clip variance at "
              f"this N, so *any* sample of these clips yields a different winner. "
              f"**An ordering claim is not supported by this metric at this sample "
              f"size** — by this work or by the paper it reproduces.\n")
        else:
            w(f"The top rank is stable ({100*top:.0f}% of resamples), so an "
              f"ordering claim is supported.\n")

    # ----------------------------------------------------------- inversions ---
    if "dir_cos" in metrics:
        w("\n## Direction inversions (`dir_cos` < 0)\n")
        w("| config | inverted | mean `mf` of inverted cells |")
        w("|---|---|---|")
        for c in order:
            v = [r for r in groups[c] if r["dir_cos"] is not None]
            inv = [r for r in v if r["dir_cos"] < 0]
            mfv = [r["mf"] for r in inv if r.get("mf") is not None]
            w(f"| {c} | {len(inv)}/{len(v)} | "
              f"{fmt(st.mean(mfv)) if mfv else '--'} |")
        allm = [r for r in rows if r["config"] != CONTROL
                and r["dir_cos"] is not None and r.get("mf") is not None]
        inv = [r["mf"] for r in allm if r["dir_cos"] < 0]
        ok = [r["mf"] for r in allm if r["dir_cos"] >= 0]
        if inv and ok:
            w(f"\nAcross all method cells, inverting the motion costs "
              f"{st.mean(ok) - st.mean(inv):.3f} of MF "
              f"({st.mean(ok):.3f} correct vs {st.mean(inv):.3f} inverted).\n")

    text = "\n".join(out)
    if args.out:
        open(args.out, "w", encoding="utf-8").write(text)
        print(f"wrote {args.out}")
    else:
        # The console codepage may not be UTF-8 (GBK on a zh Windows shell),
        # and the tables carry a Greek delta. Write bytes, not str.
        sys.stdout.buffer.write((text + "\n").encode("utf-8", "replace"))


if __name__ == "__main__":
    main()
